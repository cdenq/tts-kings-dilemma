"""Sync TTS object scripts between src/ (source of truth) and .tts/objects
(the TTS Lua extension's staging folder).

    python master_sync.py push [--dry-run]     src/ -> .tts/objects
    python master_sync.py pull [--dry-run]     .tts/objects -> src/
    python master_sync.py add <guid or name>   start tracking an object from .tts/objects

A file anywhere under src/ is tied to a TTS object by a tag on its own line:

    -- tts: 7161d6              (Lua; use "Global" for the global script)
    <!-- tts: 7161d6 -->        (XML UI)

so files can be named and moved freely. Files without a tag (like src/lib/*)
are not synced directly. Objects in the game with no tagged file are ignored.

A line "-- sync:include <path>" is replaced on push by the contents of that
file (path relative to src/), so several objects can share one script.
Files using includes are never overwritten by pull; edit src/ instead.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
TTS = ROOT / ".tts" / "objects"
EXTS = (".lua", ".xml")
TAG = re.compile(rb"^(?:--|<!--) tts: (\w+)", re.M)
INCLUDE = re.compile(rb"^-- sync:include (\S+)[ \t]*\r?$", re.M)


def tts_key(path: Path):
    """Identity of a staging file: (guid or 'Global', extension)."""
    stem = path.stem  # "Duke of Coden.7161d6" or "Global"
    return stem.rsplit(".", 1)[-1], path.suffix


def index_tts():
    return {tts_key(p): p for p in sorted(TTS.iterdir()) if p.is_file() and p.suffix in EXTS}


def index_src():
    files = {}
    for p in sorted(SRC.rglob("*")):
        if p.suffix not in EXTS:
            continue
        m = TAG.search(p.read_bytes())
        if not m:
            continue
        k = m.group(1).decode(), p.suffix
        if k in files:
            sys.exit(f"error: two files tagged {k[0]}{k[1]}: {rel(files[k])} and {rel(p)}")
        files[k] = p
    return files


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def build(src: Path) -> bytes:
    """The script TTS should get for this src file, with includes expanded."""
    data = src.read_bytes()
    includes = INCLUDE.findall(data)
    if not includes:
        return data

    def expand(m):
        lib = SRC / m.group(1).decode()
        if not lib.exists():
            sys.exit(f"error: {rel(src)} includes missing file {rel(lib)}")
        return lib.read_bytes().rstrip(b"\r\n")

    sources = " + ".join([rel(src)] + [f"src/{i.decode()}" for i in includes])
    header = f"-- GENERATED by master_sync.py from {sources}. Edit those files, not this one.\n".encode()
    return header + INCLUDE.sub(expand, data)


def tag_line(key) -> bytes:
    guid, ext = key
    return (f"<!-- tts: {guid} -->\n" if ext == ".xml" else f"-- tts: {guid}\n").encode()


def same(a: bytes, b: bytes) -> bool:
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def push(dry_run: bool):
    tts_files = index_tts()
    changed = unchanged = 0
    for k, src in index_src().items():
        dst = tts_files.get(k)
        if dst is None:
            # Objects only exist in TTS; creating new files here would do nothing.
            print(f"  ? {rel(src)}: no object {k[0]} in .tts/objects (skipped)")
            continue
        data = build(src)
        if same(dst.read_bytes(), data):
            unchanged += 1
            continue
        print(f"  M {dst.name}  <-  {rel(src)}")
        if not dry_run:
            dst.write_bytes(data)
        changed += 1
    print(f"push: {'would update' if dry_run else 'updated'} {changed}, unchanged {unchanged}")


def pull(dry_run: bool):
    tts_files = index_tts()
    tracked = index_src()
    changed = unchanged = 0
    for k, src in tracked.items():
        tts = tts_files.get(k)
        if tts is None:
            print(f"  ! {rel(src)}: object {k[0]} not in .tts/objects (deleted in-game?) - left alone")
            continue
        data = tts.read_bytes()
        if not TAG.search(data):
            data = tag_line(k) + data  # never pushed yet; keep the file tracked
        if same(build(src), data):
            unchanged += 1
        elif INCLUDE.search(src.read_bytes()):
            print(f"  ! {rel(src)}: changed in TTS, but it uses sync:include - "
                  f"copy the change into src/ by hand (not pulled)")
        else:
            print(f"  M {rel(src)}  <-  {tts.name}")
            if not dry_run:
                src.write_bytes(data)
            changed += 1

    ignored = {k[0] for k in tts_files} - {k[0] for k in tracked}
    print(f"pull: {'would update' if dry_run else 'updated'} {changed}, unchanged {unchanged}, "
          f"untracked objects ignored {len(ignored)}")


def add(query: str, dry_run: bool):
    tracked = index_src()
    q = query.lower()
    matches = {k: p for k, p in index_tts().items() if q == k[0].lower() or q in p.stem.lower()}
    if not matches:
        sys.exit(f"error: nothing in .tts/objects matches {query!r}")
    for k, p in matches.items():
        if k in tracked:
            print(f"  = {p.name} (already tracked as {rel(tracked[k])})")
            continue
        data = p.read_bytes()
        if not data.strip():
            print(f"  - {p.name} (empty, skipped)")
            continue
        dst = SRC / "objects" / p.name
        print(f"  + {rel(dst)}")
        if not dry_run:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(tag_line(k) + data)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["push", "pull", "add"])
    parser.add_argument("query", nargs="?", help="for add: GUID or part of the object's name")
    parser.add_argument("--dry-run", action="store_true", help="show what would change without writing")
    args = parser.parse_args()
    if args.command == "add":
        if not args.query:
            parser.error("add needs a GUID or name")
        add(args.query, args.dry_run)
    else:
        {"push": push, "pull": pull}[args.command](args.dry_run)


if __name__ == "__main__":
    main()
